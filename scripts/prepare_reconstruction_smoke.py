"""Create identical transparent inputs for both 3D models from real ABO photos.

The retained acquisition manifest pins original bytes. Background removal uses
reviewed rembg 2.0.57 / U2NetP on CPU; no 3D inference, cameras, reference meshes,
human ratings or relevance labels are generated by this preparation command.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
from pathlib import Path
from urllib.parse import urlsplit

BACKGROUND_URL = "https://github.com/danielgatis/rembg/releases/download/v0.0.0/u2netp.onnx"
BACKGROUND_MD5 = "8e83ca70e441ab06c318d82300c84806"
MAX_MODEL_BYTES = 10_000_000


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--acquire-background-model", action="store_true", help="Opt in to a bounded U2NetP download, less than 10 MB, verified against rembg's official MD5.")
    parser.add_argument("--restore-missing-sources", action="store_true", help="Restore omitted real source JPEGs from the existing immutable acquisition manifest; exact hash checks and a 100 MB cap.")
    parser.add_argument("--max-input-side", type=int, default=1024)
    args = parser.parse_args()
    root = args.root.resolve()
    folder = root / "datasets/reconstruction_smoke"
    acquisition = json.loads((folder / "acquisition_manifest.json").read_text(encoding="utf-8"))
    rights_path = folder / "RIGHTS_AND_ATTRIBUTION.json"
    rights = json.loads(rights_path.read_text(encoding="utf-8")) if rights_path.exists() else {}
    redistributable_ids = set()
    if rights.get("redistributable") and rights.get("licence") == "CC-BY-4.0":
        if sha((folder / "SOURCE_LICENSE_CC_BY_4_0.txt").read_bytes()) != rights.get("licence_sha256"):
            raise RuntimeError("Smoke-photo redistribution licence hash differs")
        redistributable_ids = set(rights.get("objects", []))
    transferred_sources = 0
    for item in acquisition["objects"]:
        source_path = (root / item["source_image"]).resolve()
        if not source_path.is_relative_to((folder / "assets").resolve()):
            raise RuntimeError("Source image path escapes the declared asset folder")
        if not source_path.exists() and args.restore_missing_sources:
            import requests
            url = item["archive_url"]
            if urlsplit(url).netloc != "amazon-berkeley-objects.s3.amazonaws.com":
                raise RuntimeError("Only the pinned official ABO archive origin may restore source images")
            response = requests.get(url, stream=True, timeout=45)
            response.raise_for_status()
            chunks = []
            for chunk in response.iter_content(65536):
                transferred_sources += len(chunk)
                if transferred_sources > 100_000_000:
                    raise RuntimeError("Source restoration exceeds the 100 MB transfer cap")
                chunks.append(chunk)
            data = b"".join(chunks)
            if sha(data) != item["source_sha256"] or len(data) != item["source_bytes"]:
                raise RuntimeError("Pinned ABO source bytes changed; no new source version substituted")
            source_path.parent.mkdir(parents=True, exist_ok=True)
            with source_path.open("xb") as stream:
                stream.write(data)
        if not source_path.is_file() or sha(source_path.read_bytes()) != item["source_sha256"]:
            raise RuntimeError("Missing/changed source photo; use --restore-missing-sources for omitted assets")
    # Repeated successful preparation verifies the frozen bytes without touching them.
    existing = []
    for item in acquisition["objects"]:
        image_path = folder / "assets" / f"{item['object_id']}-rgba.png"
        metadata_path = folder / f"{item['object_id']}-preparation.json"
        if not image_path.is_file() or not metadata_path.is_file():
            break
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        if sha(image_path.read_bytes()) != metadata["prepared_sha256"]:
            raise RuntimeError("Existing prepared image hash differs; no overwrite performed")
        existing.append(item["object_id"])
    if len(existing) == len(acquisition["objects"]) and (folder / "objects.csv").exists():
        print(json.dumps({"status": "verified_existing", "prepared_inputs": len(existing), "source_bytes_restored": transferred_sources,
                          "gpu_inference_performed": False}, indent=2))
        return
    model_home = root / "models/background_removal"
    model_home.mkdir(parents=True, exist_ok=True)
    model_path = model_home / "u2netp.onnx"
    if not model_path.exists():
        if not args.acquire_background_model:
            raise SystemExit("Missing reviewed background model; use --acquire-background-model after inspecting its size/licence.")
        import requests
        response = requests.get(BACKGROUND_URL, stream=True, timeout=45)
        response.raise_for_status()
        chunks, transferred = [], 0
        for chunk in response.iter_content(65536):
            transferred += len(chunk)
            if transferred > MAX_MODEL_BYTES:
                raise RuntimeError("Background model exceeds the 10 MB acquisition limit")
            chunks.append(chunk)
        data = b"".join(chunks)
        if hashlib.md5(data).hexdigest() != BACKGROUND_MD5:
            raise RuntimeError("Background model checksum mismatch; no file written")
        model_path.write_bytes(data)
    model_bytes = model_path.read_bytes()
    if hashlib.md5(model_bytes).hexdigest() != BACKGROUND_MD5:
        raise RuntimeError("Existing background model checksum mismatch")
    os.environ["U2NET_HOME"] = str(model_home)
    from PIL import Image
    import numpy as np
    import rembg
    from stylesphere.datasets import OBJECT_FIELDS
    session = rembg.new_session("u2netp", providers=["CPUExecutionProvider"])
    if session.inner_session.get_providers() != ["CPUExecutionProvider"]:
        raise RuntimeError("Background preparation must use CPU only")
    rows, prepared = [], []
    for item in acquisition["objects"]:
        original_path = root / item["source_image"]
        if sha(original_path.read_bytes()) != item["source_sha256"]:
            raise RuntimeError("Original real-photo hash differs from acquisition record")
        with Image.open(original_path) as image:
            rgb = image.convert("RGB")
        original_size = list(rgb.size)
        rgb.thumbnail((args.max_input_side, args.max_input_side), Image.Resampling.LANCZOS)
        processed = rembg.remove(rgb, session=session, alpha_matting=False, post_process_mask=False).convert("RGBA")
        alpha = np.asarray(processed.getchannel("A"))
        if alpha.min() != 0 or alpha.max() < 250 or not (0 < np.mean(alpha > 127) < 1):
            raise RuntimeError("Prepared alpha mask failed nonempty/transparency checks")
        image_path = folder / "assets" / f"{item['object_id']}-rgba.png"
        metadata_path = folder / f"{item['object_id']}-preparation.json"
        expected = json.loads(metadata_path.read_text(encoding="utf-8")) if metadata_path.exists() else None
        import io
        encoded = io.BytesIO()
        processed.save(encoded, format="PNG")
        prepared_bytes = encoded.getvalue()
        if expected and sha(prepared_bytes) != expected["prepared_sha256"]:
            raise RuntimeError("Regenerated preparation differs from the frozen input; check exact dependency versions")
        if image_path.exists():
            if image_path.read_bytes() != prepared_bytes:
                raise RuntimeError("Existing prepared input differs; no overwrite performed")
        else:
            with image_path.open("xb") as stream:
                stream.write(prepared_bytes)
        metadata = {"input_kind": "real_catalogue_photo", "synthetic": False, "original_source_image": item["source_image"],
                    "source_id": item["object_id"].removeprefix("abo-"), "source_url": item["archive_url"],
                    "original_image": item["source_image"], "prepared_image_sha256": sha(image_path.read_bytes()),
                    "original_sha256": item["source_sha256"], "original_size": original_size, "prepared_size": list(processed.size),
                    "prepared_sha256": sha(image_path.read_bytes()), "resize": {"maximum_side": args.max_input_side, "filter": "PIL LANCZOS", "preserve_aspect_ratio": True},
                    "background_removal": {"library": "rembg", "version": "2.0.57", "model": "u2netp", "source_url": BACKGROUND_URL,
                                           "model_sha256": sha(model_bytes), "model_md5": BACKGROUND_MD5, "model_bytes": len(model_bytes),
                                           "providers": session.inner_session.get_providers(), "alpha_matting": False, "post_process_mask": False},
                    "alpha_foreground_fraction_over_127": float(np.mean(alpha > 127)), "human_review_status": "pending",
                    "same_prepared_input_for_models": ["SPAR3D", "Stable Fast 3D"], "reference_geometry_available": False,
                    "camera_calibration_available": False, "metric_eligibility": {"geometry": False, "silhouette": False, "render_similarity": False}}
        if not metadata_path.exists():
            metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
        category = "footwear" if item["listing"]["product_type"][0]["value"] == "SHOES" else "handbag"
        rows.append({"object_id": item["object_id"], "source_image": image_path.relative_to(root).as_posix(), "category": category,
                     "source_dataset": "Amazon Berkeley Objects", "reference_mesh": "", "camera_info": "",
                     "preparation_metadata": metadata_path.relative_to(root).as_posix(), "geometry_eligible": "false", "silhouette_eligible": "false",
                     "render_similarity_eligible": "false", "licence": "CC-BY-4.0", "source_revision": "sha256:" + acquisition["source_metadata_sha256"],
                     "image_sha256": metadata["prepared_sha256"], "mesh_sha256": "",
                     "redistributable": str(item["object_id"] in redistributable_ids).lower()})
        prepared.append({"object_id": item["object_id"], "input_sha256": metadata["prepared_sha256"], "prepared_size": list(processed.size)})
    manifest_path = folder / "objects.csv"
    if not manifest_path.exists():
        with manifest_path.open("w", encoding="utf-8", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=OBJECT_FIELDS)
            writer.writeheader()
            writer.writerows(rows)
    print(json.dumps({"prepared": prepared, "background_model_bytes": len(model_bytes), "gpu_inference_performed": False,
                      "geometric_metrics_eligible": False, "human_review_status": "pending"}, indent=2))


if __name__ == "__main__":
    main()
